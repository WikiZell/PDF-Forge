#!/usr/bin/env node
// Generates THIRD_PARTY_LICENSES from the Rust dependency tree (Windows x64 target) and the
// production npm dependencies, and fails if a disallowed licence is found.
//   node scripts/gen-licenses.mjs          write THIRD_PARTY_LICENSES
//   node scripts/gen-licenses.mjs --check  fail if the committed file is stale or a licence is disallowed
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

// Spec: permissive or LGPL-compatible only; no AGPL (MuPDF/iText), no plain GPL/SSPL/proprietary.
const DISALLOWED = /\b(AGPL|SSPL|BUSL|Commons-Clause)\b|(^|[^L])GPL(?!.*LGPL)/;

const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-pc-windows-msvc"], { cwd: root, maxBuffer: 1 << 28 }).toString(),
);
const workspace = new Set(meta.workspace_members);
const rust = meta.packages
  .filter((p) => !workspace.has(p.id))
  .map((p) => ({ name: p.name, version: p.version, license: p.license ?? (p.license_file ? `see ${p.license_file}` : "UNKNOWN"), repo: p.repository ?? "" }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const prod = new Set();
const walk = (name) => {
  if (prod.has(name)) return;
  const e = lock.packages[`node_modules/${name}`];
  if (!e) return;
  prod.add(name);
  for (const d of Object.keys({ ...(e.dependencies ?? {}), ...(e.peerDependencies ?? {}) })) walk(d);
};
for (const d of Object.keys(pkg.dependencies ?? {})) walk(d);
const npm = [...prod].sort().map((n) => {
  const e = lock.packages[`node_modules/${n}`];
  return { name: n, version: e.version, license: e.license ?? "UNKNOWN", repo: "" };
});

const bundled = [
  { name: "PDFium (pdfium.dll)", version: "chromium/8125 via bblanchon/pdfium-binaries", license: "BSD-3-Clause / Apache-2.0", repo: "https://pdfium.googlesource.com/pdfium/ ; licence text ships as PDFIUM-LICENSE.txt" },
  { name: "Dancing Script (font)", version: "-", license: "OFL-1.1", repo: "https://github.com/googlefonts/DancingScript" },
  { name: "Great Vibes (font)", version: "-", license: "OFL-1.1", repo: "https://github.com/googlefonts/great-vibes" },
  { name: "Caveat (font)", version: "-", license: "OFL-1.1", repo: "https://github.com/googlefonts/caveat" },
  { name: "Sacramento (font)", version: "-", license: "OFL-1.1", repo: "https://github.com/googlefonts/sacramento" },
];

const bad = [...rust, ...npm, ...bundled].filter((p) => p.license === "UNKNOWN" || DISALLOWED.test(p.license));

const fmt = (list) => list.map((p) => `${p.name} ${p.version}\n    License: ${p.license}${p.repo ? `\n    Source:  ${p.repo}` : ""}`).join("\n\n");
const fontLicenses = readdirSync(join(root, "licenses/fonts")).sort()
  .map((f) => `----- ${f} -----\n${readFileSync(join(root, "licenses/fonts", f), "utf8").trim()}`).join("\n\n");

const text = `PDF Forge — third-party software
================================

Generated by scripts/gen-licenses.mjs. Do not edit by hand.
Counts: ${rust.length} Rust crates, ${npm.length} npm packages, ${bundled.length} bundled binaries/fonts.

== Bundled binaries and fonts ==

${fmt(bundled)}

== Rust crates (Windows x64 build) ==

${fmt(rust)}

== npm packages (production, bundled into the UI) ==

${fmt(npm)}

== Font licence texts (SIL Open Font License 1.1) ==

${fontLicenses}
`;

if (bad.length) {
  console.error("Disallowed or unknown licences:\n" + bad.map((p) => `  ${p.name} ${p.version}: ${p.license}`).join("\n"));
  process.exit(1);
}
const out = join(root, "THIRD_PARTY_LICENSES");
if (check) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
    console.error("THIRD_PARTY_LICENSES is out of date. Run: node scripts/gen-licenses.mjs");
    process.exit(1);
  }
  console.log("THIRD_PARTY_LICENSES is up to date.");
} else {
  writeFileSync(out, text);
  console.log(`Wrote THIRD_PARTY_LICENSES (${rust.length} crates, ${npm.length} npm packages).`);
}
